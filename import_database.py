"""Import a recipient-encrypted database from a trusted main-branch workflow run."""

import argparse
import hashlib
import os
from pathlib import Path
import re
import subprocess
import tempfile

from backup_crypto import age


ROOT = Path(__file__).resolve().parent


def import_database(artifact, identity, sha256, cache_key, receipt):
    if not re.fullmatch(r"[0-9a-f]{64}", sha256) or not re.fullmatch(r"qualified-db-v1-[0-9a-f]{64}", cache_key):
        raise ValueError("Copy the ciphertext SHA-256 and cache identity from the trusted main workflow run")
    if os.path.lexists(receipt):
        raise ValueError("Choose a new receipt path in your private directory")
    receipt = receipt.absolute()
    executable = age()
    with tempfile.TemporaryDirectory(prefix=".database-import-", dir=receipt.parent) as folder:
        work = Path(folder)
        # Pass exactly one native identity to age. This also excludes plugin identities.
        with identity.open("rb") as source:
            key_data = source.read(8193)
        keys = [line for line in key_data.splitlines() if line and not line.startswith(b"#")]
        if len(key_data) > 8192 or len(keys) != 1 or not re.fullmatch(rb"AGE-SECRET-KEY-1[AC-HJ-NP-Z02-9]{58}", keys[0]):
            raise ValueError("Use the native X25519 identity file generated by age-keygen")
        key = work / "identity"
        key.write_bytes(keys[0] + b"\n")
        key.chmod(0o600)
        bundle = work / "bundle.tar"
        # Hash and decrypt the same private copy, even if the download path changes.
        with tempfile.TemporaryFile(dir=work) as ciphertext, artifact.open("rb") as source:
            digest = hashlib.sha256()
            while chunk := source.read(1024 * 1024):
                digest.update(chunk)
                ciphertext.write(chunk)
            if digest.hexdigest() != sha256:
                raise ValueError("Ciphertext SHA-256 differs from the trusted workflow summary")
            ciphertext.seek(0)
            with bundle.open("xb") as output:
                subprocess.run([executable, "--decrypt", "--identity", str(key)],
                               stdin=ciphertext, stdout=output, check=True)
        subprocess.run(["bash", "scripts/ci/database_bundle.sh", "import-verified", str(bundle), str(receipt)],
                       cwd=ROOT, env={**os.environ, "CACHE_KEY": cache_key}, check=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--artifact", required=True, type=Path)
    parser.add_argument("--identity", required=True, type=Path)
    parser.add_argument("--sha256", required=True, help="Ciphertext digest from the trusted workflow summary")
    parser.add_argument("--cache-key", required=True, help="Exact cache identity from the same run")
    parser.add_argument("--receipt", required=True, type=Path, help="New receipt in a private directory")
    args = parser.parse_args()
    try:
        import_database(**vars(args))
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        raise SystemExit(str(exc)) from None
    print("Verified database receipt:", args.receipt.absolute())
